#!/bin/sh
set -eu
cd /Users/hherb/src/allrpcs
export ALLRPCS_CHARACTER_MODEL_COMPOSITION_DISABLED=1
export ALLRPCS_ORDINARY_PARTICIPATION_SMOKE_MODEL=1
for mode in normal muted missing captions-off; do
 ALLRPCS_MATERIAL_MAIN_CHECK=1 ALLRPCS_MATERIAL_ACTION_MODE="$mode" ALLRPCS_MATERIAL_RESULT_PATH="/tmp/allrpcs-material-action-$mode.txt" godot --headless --path game --quit-after 1000 > "/tmp/allrpcs-material-action-$mode.log" 2>&1
